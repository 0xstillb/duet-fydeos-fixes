static ssize_t (*real_write_fn)(int, const void *, size_t);

__attribute__((constructor))
static void duet5_uhid_shim_init(void) {
    void *symbol = dlsym(RTLD_NEXT, "write");
    memcpy(&real_write_fn, &symbol, sizeof(symbol));
}

ssize_t write(int fd, const void *buffer, size_t count) {
    if (real_write_fn == NULL) {
        errno = ENOSYS;
        return -1;
    }

    if (buffer != NULL && count == UHID_EVENT_SIZE) {
        const unsigned char *event = (const unsigned char *)buffer;
        uint32_t event_type = 0;
        uint16_t report_size = 0;
        memcpy(&event_type, event, sizeof(event_type));
        memcpy(&report_size, event + UHID_RD_SIZE_OFFSET, sizeof(report_size));

        if (event_type == UHID_CREATE2 &&
            report_size == sizeof(duet5_truncated_map) &&
            memcmp(event + UHID_RD_DATA_OFFSET,
                   duet5_truncated_map,
                   sizeof(duet5_truncated_map)) == 0) {
            unsigned char repaired_event[UHID_EVENT_SIZE];
            const uint16_t repaired_size = sizeof(duet5_repaired_map);
            memcpy(repaired_event, event, sizeof(repaired_event));
            memcpy(repaired_event + UHID_RD_SIZE_OFFSET,
                   &repaired_size,
                   sizeof(repaired_size));
            memset(repaired_event + UHID_RD_DATA_OFFSET, 0, UHID_RD_DATA_MAX);
            memcpy(repaired_event + UHID_RD_DATA_OFFSET,
                   duet5_repaired_map,
                   sizeof(duet5_repaired_map));
            return real_write_fn(fd, repaired_event, count);
        }
    }

    return real_write_fn(fd, buffer, count);
}
